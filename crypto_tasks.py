# 任务 4：加密盘面分析
# ══════════════════════════════════════════════════════════════════════════════
crypto_analyzer_task = Task(
    description=(
        "基于核查员给出的【修正后的情报】，对 {today} 的加密盘面做一次专业、有观点的深度分析。"
        "凡标注❌已修正的数据以修正值为准；⚠️无法核验的数据不要引用。"
        "同时参考【往期预测验证】的校准结论，并先调用 get_crypto_track_record 查看自身历史战绩，"
        "在弱项维度上**主动降低表态强度、补充证伪条件**。\n\n"
        "分析框架（缺一不可）：\n"
        "1. 价格与量价结构：结合 BTC/ETH 收盘、成交额与量能变化，判断放量突破/缩量整理/放量下杀，"
        "是否量价背离；给出均线结构（多头/空头/纠缠）与趋势阶段。\n"
        "2. 衍生品与杠杆（重点）：解读资金费率（正负与极端值→多头/空头拥挤）、未平仓 OI 变化"
        "（增仓上涨＝趋势健康、增仓下跌＝空头进场、减仓＝平仓/去杠杆）、多空账户比与吃单比、"
        "近一日爆仓结构、期货基差（升贴水）。据此判断是否存在**杠杆拥挤与挤兑风险**。\n"
        "3. 市场结构与轮动：用总市值、BTC/ETH 主导率、ETH/BTC 汇率判断资金是向 BTC 集中（防御）"
        "还是向 ETH/山寨扩散（进攻），以及轮动所处阶段。\n"
        "4. ETF 资金面：结合 get_crypto_etf_flows 的成交额与（若有）净流入/流出，判断 ETF 渠道资金"
        "是流入还是流出、对价格是支撑还是拖累，关注资金与价格的背离。\n"
        "5. 情绪：结合恐贪指数判断市场是否处于极端（过度贪婪易回调、极度恐慌易反弹）。\n"
        "6. 技术分析：给出 BTC、ETH 的关键支撑位与压力位（**写具体点位**），"
        "并写成可被机器解析的规范格式（如「BTC 上方压力 86000、下方支撑 80000」「跌破 81000 转空」）。\n"
        "7. 预判与策略（多空点位）：给出对次日及未来 1-2 周的走势预判（乐观/中性/悲观三情景及概率），"
        "并给出**明确、可执行的多空点位**——做多入场区间 / 止损 / 止盈目标、做空入场区间 / 止损 / 止盈目标，"
        "以及各自仓位与触发条件，并说明**证伪条件**。点位必须写成可机器核验格式，例如"
        "「BTC 回踩 80000 支撑做多，止损 78500，目标 86000」「ETH 反弹 2600 压力做空，止损 2700，目标 2400」。\n\n"
        "要求：结论先行、逻辑支撑、敢下判断，但必须说明什么情况会证伪。数据存疑时调用工具复核。"
    ),
    expected_output=(
        "一份加密盘面分析 MARKDOWN：价量与趋势结论、衍生品/杠杆解读、市场结构与轮动判断、ETF 资金面解读、"
        "明确的 BTC/ETH 支撑压力位、**多空点位表（做多/做空的入场、止损、止盈、仓位）**、"
        "分情景的次日及短期走势预判（含概率）、可执行策略与证伪条件。"
    ),
    agent=crypto_analyzer,
    context=[crypto_fact_check_task, crypto_review_task],
    output_file="outputs/crypto_02_analysis_{today}.md",
)

