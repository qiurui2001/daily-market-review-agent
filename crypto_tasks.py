# 任务 3：往期预测验证
# ══════════════════════════════════════════════════════════════════════════════
crypto_review_task = Task(
    description=(
        "今天是 {today}。请对【往期《加密复盘》里的预测】做一次回溯验证，形成『预测→实际→归因』闭环。\n\n"
        "**判分口径（重要）**：命中/偏离一律以工具 auto_verify_crypto_predictions 的**确定性结果**为准"
        "（它用真实 BTC/ETH 日 K 判定了压力/支撑/突破/跌破位是否触及、方向是否兑现），"
        "你只负责补充「归因」，不得自行改写命中结论。\n\n"
        "步骤（必须调用工具）：\n"
        "1. 调用 auto_verify_crypto_predictions：days_back=30、exclude_date=\"{today}\"，拿到逐条核验表。\n"
        "2. 必要时用 get_crypto_overview / get_crypto_kline 复核工具给出的实际点位。\n"
        "3. 对每条补充归因（逻辑错、数据错，还是被突发消息/清算瀑布扰动；点位为何触及或偏离）。\n"
        "4. 调用 get_crypto_prediction_stats 取全时段与滚动命中率作为概览。\n"
        "5. 调用 verify_crypto_ledger_integrity 确认加密预测台账（哈希链）未被改动；有警示须写进报告。\n"
        "6. 最后给「校准结论」：本期应吸取的经验、需修正的惯性误判。\n\n"
        "红线：命中/偏离以自动核验为准；**严禁编造往期预测**。若无往期报告，如实说明『首次运行』。"
    ),
    expected_output=(
        "一份《往期预测验证》MARKDOWN：验证概览（含确定性滚动命中率）、逐条验证表"
        "（报告日期/币种/预测内容/实际走势/结论[采用自动核验]/偏差/归因）、校准结论。"
        "无往期报告时给出空表与说明。"
    ),
    agent=crypto_review_validator,
    context=[crypto_fact_check_task],
    output_file="outputs/crypto_01c_review_{today}.md",
)

