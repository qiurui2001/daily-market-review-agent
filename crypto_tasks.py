# 任务 2：事实核查
# ══════════════════════════════════════════════════════════════════════════════
crypto_fact_check_task = Task(
    description=(
        "只看上一步【加密研究员】的原始情报，对它做独立事实核查，目的是**减少幻觉**。"
        "不做任何行情分析或预测。\n\n"
        "核查方法（必须亲自调用工具）：\n"
        "1. 价格/涨跌幅/成交额/全球市值/主导率/恐贪 → 用 get_crypto_overview、get_crypto_global、"
        "get_crypto_sentiment 重新取数，逐项比对。\n"
        "2. 均线、区间高低点、阶段涨跌、波动率 → 用 get_crypto_kline 复核。\n"
        "3. 资金费率、OI、多空比、爆仓、基差 → 用 get_crypto_derivatives 复核，**特别注意口径与单位**"
        "（资金费率是每期还是年化？OI 是张数还是美元？多空比是账户比还是吃单比？）。\n"
        "4. ETF 成交额与（若有）净流入/流出 → 用 get_crypto_etf_flows 复核，区分「成交额代理」与"
        "「真实净申赎」，不要把成交额当成净流入；**若研究员写出的净申赎金额无法在本轮实际抓取中复现，"
        "一律判定 ⚠️无法核验并标注『疑似编造』。**\n"
        "5. 消息面用 get_crypto_news 抽查，注意时间窗与事件是否张冠李戴。\n\n"
        "对每一项给出判定：✅一致 / ❌错误（附工具值与研究员值）/ ⚠️无法核验。"
        "严禁替研究员补写或美化，严禁输出预测。最后给出「修正后的情报」供下游使用。"
    ),
    expected_output=(
        "一份事实核查报告 MARKDOWN，包含：核对结论、差异清单（项目/研究员值/工具值/判定/说明）、"
        "无法核验项清单、修正后的完整情报（不含预测）。"
    ),
    agent=crypto_fact_checker,
    context=[crypto_researcher_task],
    output_file="outputs/crypto_01b_factcheck_{today}.md",
)

