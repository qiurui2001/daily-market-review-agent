# 任务 1：信息收集
# ══════════════════════════════════════════════════════════════════════════════
crypto_researcher_task = Task(
    description=(
        "今天是 {today}（UTC 日）。请完成当日 **BTC / ETH** 的盘后信息收集，"
        "务必调用工具拿到**真实数据**，不要凭记忆编写。\n\n"
        "收集范围（按优先级）：\n"
        "1. 行情总览：调用「get_crypto_overview」拿到 BTC、ETH 的收盘价、涨跌幅、7d/30d 涨跌、"
        "24h 高低与成交额，以及全球总市值、主导率与恐贪指数。\n"
        "2. 量价结构：调用「get_crypto_kline」查看 BTC、ETH 近 120 根日 K，"
        "记录均线（MA20/50/200）位置、近 20 日高低点、阶段涨跌与实现波动率。\n"
        "3. 衍生品（加密核心）：调用「get_crypto_derivatives」分别获取 BTC、ETH 的"
        "资金费率（每期与年化）、未平仓 OI 及其变化、多空账户比/吃单比、近一日多空爆仓、期货基差。\n"
        "4. 市场结构：调用「get_crypto_global」拿到总市值、BTC/ETH 主导率、ETH/BTC 汇率及其 7d/30d 变化。\n"
        "5. ETF 资金面：调用「get_crypto_etf_flows」拿到美国现货 ETF（IBIT/FBTC/ETHA/FETH 等）的"
        "价格、涨跌、成交额及合计（资金关注度代理）；再用「web_search」检索"
        "「比特币现货ETF 净流入 净流出」「以太坊ETF 资金流」尽力补齐当日净申赎方向。"
        "**净申赎数字必须来自本轮实际抓取到的页面或工具返回；取不到就写『未获取（数据源受限）』，"
        "严禁凭记忆编造具体净流入/流出金额或引用取不到的站点（如 Farside）。**\n"
        "6. 情绪：调用「get_crypto_sentiment」拿到恐慌与贪婪指数当前值与近期趋势。\n"
        "7. 消息面：调用「get_crypto_news」拿最新加密要闻；再用「web_search」检索"
        "「比特币 以太坊 {today} 行情 原因」「BTC ETF 资金流 监管」，必要时用「fetch_webpage」深读。\n\n"
        "输出要求：分「行情 / 量价结构 / 衍生品与杠杆 / 市场结构 / ETF 资金面 / 情绪 / 消息面」七节，"
        "每条信息必须带具体数字、时间与来源，并标注利好/利空/中性。不要写分析结论，只做客观汇总。"
    ),
    expected_output=(
        "一份结构化的加密原始情报 MARKDOWN，包含：\n"
        "- 行情：BTC/ETH 收盘价与涨跌幅、全球市值与主导率\n"
        "- 量价结构：均线、区间高低点、阶段涨跌、波动率\n"
        "- 衍生品与杠杆：资金费率（年化）、OI 及变化、多空比、爆仓、基差\n"
        "- 市场结构：主导率、ETH/BTC 汇率\n"
        "- ETF 资金面：主要现货 ETF 成交额与（若有）净流入/流出\n"
        "- 情绪：恐贪指数\n"
        "- 消息面：当日重要利好利空（含来源）\n"
        "全部为带数字的事实，不含主观判断。"
    ),
    agent=crypto_researcher,
    output_file="outputs/crypto_01_research_{today}.md",
)

