# 任务 5：撰写（含 K 线图）
# ══════════════════════════════════════════════════════════════════════════════
crypto_writer_task = Task(
    description=(
        "把研究院的分析整理、润色成一份完整的 {today} **《加密复盘》报告**"
        "（正文即最终交付物，后续有独立任务负责存档与发送，你只需把正文写好）。\n\n"
        "第一步（重要）：调用 generate_crypto_charts 生成 BTC/ETH 日 K 线图（近 120 日），"
        "它会返回若干行 Markdown 图片语法。\n\n"
        "报告结构（**精简版，务必克制篇幅**）：\n"
        "# 加密复盘 | {today}\n"
        "> **一句话结论**：<40–80 字，定性 + 最关键理由>\n"
        "## 一、行情\n"
        "  用 **Markdown 表格** 列出 BTC/ETH：币种 / 收盘价(USDT) / 当日涨跌 / 7d / 30d / 量价定性"
        "（列数对齐），并附一行全球总市值、BTC/ETH 主导率、恐贪指数。"
        "  表格下方**只插入 2 张 K 线图**（BTC、ETH）——从 generate_crypto_charts 返回里挑这两行**原样插入**。\n"
        "## 二、杠杆与结构（**要点式，禁止粘贴整块表格**）\n"
        "  用 5–7 条要点覆盖四块：①衍生品与杠杆（资金费率年化 / OI 变化 / 多空比 / 爆仓 / 基差，2–3 条）；"
        "②市场结构（主导率、ETH/BTC 汇率，1–2 条）；③ETF 资金面（成交额与净流入/流出，1–2 条，取不到就如实说明）；"
        "④情绪与消息面（恐贪 + 关键事件，≤2 条）。每条约一句话。\n"
        "## 三、后市预判与操作策略\n"
        "  1) 分情景（乐观/中性/悲观 + 概率%），每情景 1–2 句。\n"
        "  2) **多空点位表**（Markdown 表格）：币种 / 方向 / 入场区间 / 止损 / 止盈目标 / 仓位 / 触发条件 / 证伪信号。\n"
        "  3) **点位口径句（可机器核验）**：如「BTC 回踩 80000 支撑做多，止损 78500，目标 86000」"
        "「ETH 反弹 2600 压力做空，止损 2700，目标 2400」。\n"
        "  凡涉及点位，必须写成可被机器解析的规范格式；系统会在下一 UTC 日用真实行情自动核验。\n"
        "## 四、往期验证与风险提示\n"
        "  先写一行**确定性滚动命中率**（采用校验员输出里的统计），再给**精简验证表**"
        "（报告日期 / 币种 / 预测 / 实际 / 结论 / 归因，**最多 5 行**）；无往期则写「首次运行，暂无往期可验证」。"
        "  末尾 2–3 句风险提示（强调杠杆风险）+ 不构成投资建议的免责声明。\n\n"
        "写作要求：\n"
        "- **精简优先**：全文尽量控制在 ~1 屏内，信息密度高、不堆料；能一句话说清就不写三句。\n"
        "- 结论先行，重点用 **加粗**；所有表格规范、列数一致。\n"
        "- 保留关键数字与点位，不得杜撰数据；缺失数据如实说明。\n"
        "- 报告要完整收尾，不要写到一半中断。"
    ),
    expected_output=(
        "一份**精简**的《加密复盘》报告 MARKDOWN：一句话结论 + BTC/ETH 行情表与 2 张 K 线图 + "
        "要点式杠杆与结构 + 情景预判与多空点位表（可机器核验）+ 一行命中率与精简验证表 + 风险提示，"
        "篇幅克制、已完整结尾。"
    ),
    agent=crypto_writer,
    context=[crypto_analyzer_task, crypto_review_task],
    output_file="outputs/crypto_03_report_{today}.md",
)

