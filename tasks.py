# -*- coding: utf-8 -*-
"""
tasks.py —— 串行任务链
========================

数据流：researcher_task → fact_check_task → review_task → analyzer_task → writer_task → deliver_task

约定：main.py 以 inputs={"today": "YYYY-MM-DD"} 启动，任务里的 {today} 会被自动替换。
"""

from __future__ import annotations

from crewai import Task

from agents import analyzer, fact_checker, researcher, review_validator, writer

# ══════════════════════════════════════════════════════════════════════════════
# 任务 1：信息收集
# ══════════════════════════════════════════════════════════════════════════════
researcher_task = Task(
    description=(
        "今天是 {today}。请完成当日**美股**盘后信息收集，务必调用工具拿到**真实数据**，不要凭记忆编写。\n\n"
        "收集范围（按优先级）：\n"
        "1. 大盘：调用「get_market_overview」拿到标普500、纳斯达克综指、道琼斯、纳斯达克100、"
        "罗素2000 的收盘点位、涨跌幅与成交额，以及 VIX 水平。\n"
        "2. 量价结构：调用「get_index_kline」查看标普500、纳斯达克综指近 60 根日 K，"
        "记录均线位置、近 20 日高低点、近 5 日量能变化。\n"
        "3. 行业轮动：调用「get_sector_performance」拿到 11 大 SPDR 行业 ETF 当日涨跌幅排序"
        "（工具会返回 Markdown 表格），判断主线（进攻/防御）。\n"
        "4. 市场内部结构：调用「get_market_internals」记录科技七巨头表现、大小盘/成长/等权风格强弱、"
        "以及 VIX 隐含的风险偏好。\n"
        "5. 外围与宏观：调用「get_global_markets」，记录隔夜亚太/欧洲股市、美元指数、原油、黄金、美债 ETF。\n"
        "6. 消息面：调用「get_market_news」拿最新要闻；再用「web_search」检索"
        "「美股 {today} 收盘 复盘 纳指 科技股 原因」「财报 美联储」，必要时用「fetch_webpage」深读重点文章。\n\n"
        "输出要求：分「大盘 / 行业轮动 / 市场内部结构与风险偏好 / 消息面 / 外围与宏观」五节，"
        "每条信息必须带具体数字、时间与来源，并标注它是利好、利空还是中性。"
        "不要写分析结论，只做客观汇总。"
    ),
    expected_output=(
        "一份结构化的原始情报 MARKDOWN，包含：\n"
        "- 大盘：各指数收盘价与涨跌幅、VIX\n"
        "- 行业轮动：11 大 SPDR 行业 ETF 涨跌幅排序\n"
        "- 市场内部结构：科技七巨头表现、风格强弱、风险偏好\n"
        "- 消息面：当日重要利好利空（含来源）\n"
        "- 外围与宏观：亚太/欧股、美元、原油、黄金、美债\n"
        "全部为带数字的事实，不含主观判断。"
    ),
    agent=researcher,
    output_file="outputs/01_research_{today}.md",
)

# ══════════════════════════════════════════════════════════════════════════════
# 任务 2：事实核查（只审研究员，防止幻觉）
# ══════════════════════════════════════════════════════════════════════════════
fact_check_task = Task(
    description=(
        "只看上一步【研究员】的原始情报，对它做独立的事实核查，目的是**减少幻觉**。"
        "你不需要做任何行情分析或预测。\n\n"
        "核查方法（必须亲自调用工具，不能凭记忆判断）：\n"
        "1. 指数点位/涨跌幅/成交额、VIX → 用 get_market_overview 重新取数，逐项比对。\n"
        "2. 均线、区间高低点、量能表述 → 用 get_index_kline 复核。\n"
        "3. 行业板块涨跌 → 用 get_sector_performance 抽查。\n"
        "4. 科技七巨头、风格、风险偏好 → 用 get_market_internals 复核。\n"
        "5. 外围/宏观 → 用 get_global_markets 抽查；消息面用 get_market_news 抽查。\n"
        "6. 注意研究员是否把「时间窗」当成「具体事件」来写，或张冠李戴。\n\n"
        "对每一项给出判定：✅一致 / ❌错误（附工具值与研究员值）/ ⚠️无法核验（工具取不到）。\n"
        "严禁替研究员补写、猜测或美化；严禁输出任何预测性结论。\n\n"
        "最后输出「修正后的情报」：保留✅与⚠️的原始内容，把❌的错误数据替换为工具值并标注，"
        "供下游分析师直接使用。"
    ),
    expected_output=(
        "一份事实核查报告 MARKDOWN，包含：\n"
        "- 核对结论（通过率、发现的问题数量与严重度）\n"
        "- 差异清单（逐项：项目 / 研究员值 / 工具值 / 判定 / 说明）\n"
        "- 无法核验项清单\n"
        "- 修正后的完整情报（错误已更正并标注，不含预测）"
    ),
    agent=fact_checker,
    context=[researcher_task],
    output_file="outputs/01b_factcheck_{today}.md",
)

# ══════════════════════════════════════════════════════════════════════════════
# 任务 3：往期预测验证（RAG 回溯，闭环校准）
# ══════════════════════════════════════════════════════════════════════════════
review_task = Task(
    description=(
        "今天是 {today}。请对【往期复盘报告里做出的预测】做一次回溯验证，形成『预测 → 实际 → 归因』的闭环。\n\n"
        "**判分口径（重要）**：命中/偏离一律以工具 auto_verify_predictions 的**确定性结果**为准"
        "（它用真实日 K 判定了压力/支撑/突破/跌破位是否触及、方向是否兑现），你**只负责补充「归因」**，"
        "不得自行改写命中结论、也不得凭印象打分。\n\n"
        "步骤（必须调用工具，不能凭记忆）：\n"
        "1. 调用 auto_verify_predictions：days_back=30、exclude_date=\"{today}\"，"
        "拿到逐条核验表（报告日期 / 标的 / 预测内容 / 实际走势 / 结论 / 规则命中明细）。\n"
        "2. 用 retrieve_past_predictions 检索这些预测的**原文上下文**"
        "（query 建议：「下一交易日及未来1-2周 走势预判 情景 概率 支撑位 压力位 操作策略 仓位」；"
        "top_k=8、days_back=30、exclude_date=\"{today}\"），以便理解当时的推理依据。\n"
        "3. 必要时用 get_market_overview / get_index_kline 复核工具给出的实际点位。\n"
        "4. 对每条：直接采用自动核验的结论，补充「归因」（是逻辑错、数据错，还是被突发消息扰动；"
        "点位为何恰好触及或偏离；方向为何兑现或落空）。\n"
        "5. 调用 get_prediction_stats 取「全时段 + 近 5 份报告」的滚动命中率，作为验证概览。\n"
        "6. 调用 verify_ledger_integrity 确认历史预测台账（哈希链）未被动过；若有篡改警示须写进报告。\n"
        "7. 最后给「校准结论」：本期分析应吸取的经验、需要修正的惯性误判。\n\n"
        "红线：命中/偏离以 auto_verify_predictions 为准；取不到就写无法验证；**严禁编造往期预测**。"
        "若检索不到往期报告，如实说明『首次运行、无往期可验证』。"
    ),
    expected_output=(
        "一份《往期预测验证》MARKDOWN，包含：\n"
        "- 验证概览（检索到的往期报告、**确定性滚动命中率**）\n"
        "- 逐条验证表（报告日期 / 预测内容 / 实际走势 / 结论[采用自动核验] / 偏差 / 归因）\n"
        "- 校准结论（本期应吸取的经验与需修正的误判）\n"
        "无往期报告时，明确说明并可给出空表与说明。"
    ),
    agent=review_validator,
    context=[fact_check_task],
    output_file="outputs/01c_review_{today}.md",
)

# ══════════════════════════════════════════════════════════════════════════════
# 任务 4：盘面分析
# ══════════════════════════════════════════════════════════════════════════════
analyzer_task = Task(
    description=(
        "基于核查员给出的【修正后的情报】，对 {today} 的美股盘面做一次专业、有观点的深度分析。"
        "凡标注❌已修正的数据，以修正值为准；⚠️无法核验的数据不要引用或需注明。"
        "同时请参考【往期预测验证】的校准结论，主动规避此前重复出现的误判。"
        "此外，先调用 get_research_track_record 查看自身历史战绩（按能力维度/体制/视野/置信度分桶），"
        "在历史弱项（如「震荡市的方向判断」）上**主动降低表态强度、补充证伪条件**，在强项上再给高置信度。\n\n"
        "分析框架（缺一不可）：\n"
        "1. 指数量价：结合标普/纳指点位、成交额与量能变化，判断是放量上攻、缩量调整还是放量杀跌，"
        "量价是否背离。\n"
        "2. 行业轮动与主线：从 11 大行业 ETF 的强弱识别当日主线（进攻性 vs 防御性），"
        "判断资金是在抱团权重还是在扩散，主线的持续性如何。\n"
        "3. 市场内部结构：看上涨是普涨还是少数权重股拉动（等权 vs 市值加权、小盘 vs 大盘），"
        "结合科技七巨头与 VIX 判断风险偏好。\n"
        "4. 技术分析：给出标普500/纳斯达克综指的关键支撑位与压力位（要写具体点位），"
        "判断指数所处均线结构（多头/空头/纠缠）与趋势阶段。"
        "**点位必须写成可被机器解析的规范格式**（如「压力 7800」「支撑 7600」「跌破 7650」「站稳 7800」），"
        "以便系统在下一交易日自动核验这些预测。\n"
        "5. 外围与宏观：评估美元、美债（利率方向）、原油、黄金、亚太欧股对美股的边际影响，"
        "以及当日消息/财报/美联储表态的影响。\n"
        "6. 预判与策略：给出对次日及未来 1-2 周的走势预判（分乐观/中性/悲观三种情景及各自概率），"
        "并给出对应的仓位与操作建议（波段视角，说明什么信号出现该加仓/减仓/止损）。\n\n"
        "要求：结论先行、逻辑支撑、敢下判断，但必须说明「什么情况会证伪」。"
        "如对数据仍有疑问，可调用工具再次核对。"
    ),
    expected_output=(
        "一份盘面分析 MARKDOWN，包含：\n"
        "- 指数量价与行业轮动结论\n"
        "- 明确的支撑位、压力位点位\n"
        "- 市场内部结构与风险偏好定位\n"
        "- 分情景的次日及短期走势预判（含概率）\n"
        "- 可执行的仓位与操作策略，以及证伪条件"
    ),
    agent=analyzer,
    context=[fact_check_task, review_task],
    output_file="outputs/02_analysis_{today}.md",
)

# ══════════════════════════════════════════════════════════════════════════════
# 任务 5：撰写（含 K 线图）
# ══════════════════════════════════════════════════════════════════════════════
writer_task = Task(
    description=(
        "把研究院的分析整理、润色成一份完整的 {today} **每日美股复盘报告**（正文即最终交付物，"
        "后续会有独立任务负责存档与发送，你这里只需把正文写好）。\n\n"
        "第一步（重要）：调用 generate_index_charts 生成大盘 K 线图（近三个月），"
        "它会返回若干行 Markdown 图片语法。\n\n"
        "报告结构：\n"
        "# 美股复盘 | {today}\n"
        "## 一、今日大盘\n"
        "  1) 用一个 **Markdown 表格** 列出主要指数：指数 / 收盘 / 涨跌幅 / 近5日量能变化 / 量价定性，"
        "并给出 VIX。表格必须列数对齐、分隔行与表头列数一致（例如 5 列就写 5 个 |---|）。\n"
        "  2) 表格下方，把 generate_index_charts 返回的图片行 **原样插入**，作为大盘走势的直观展示。\n"
        "## 二、往期预测验证\n"
        "  先在开头写一行**滚动命中率统计**（采用校验员输出里的 get_prediction_stats 结果，"
        "如「全时段✅命中率 X%、宽松命中率 Y%；近5份 …」），再用 **Markdown 表格** 呈现："
        "报告日期 / 预测内容（含关键点位）/ 实际走势 / 结论（✅命中 / ⚠️部分命中 / ❌偏离）/ 偏差 / 归因；"
        "表后写 2-3 句校准结论。若往期无报告，写明「首次运行，暂无往期可验证」。\n"
        "## 三、行业轮动与资金主线\n"
        "  **做法固定**：调用 get_sector_performance，把返回的 11 大行业 ETF Markdown 表格 "
        "**逐字原样粘贴**（不要改写、不要精简、不要把有数据的单元格写成「数据缺失」），"
        "然后在表格后写 2-3 句主线与退潮点评（进攻/防御、持续性）。\n"
        "## 四、市场内部结构与技术（龙头/风格、支撑压力位、趋势）\n"
        "## 五、消息面与外围（美元、美债、原油、黄金、亚太欧股）\n"
        "## 六、后市预判与操作策略（含仓位建议与风险提示）\n"
        "  **写法要求（重要）**：凡涉及点位，必须写成可被机器解析的规范格式，"
        "如「标普500 上方压力 7850、下方支撑 7700」「纳指跌破 27000 减仓」，"
        "并明确标注方向与情景（乐观/中性/悲观及概率）；系统会在下一交易日用真实行情自动核验这些预测。\n\n"
        "写作要求：\n"
        "- 结论先行，语言专业但通俗，重点用 **加粗**。\n"
        "- 所有表格都必须是规范的 Markdown 表格，列数前后一致。\n"
        "- 保留所有关键数字和点位，不得杜撰数据；对缺失数据要如实说明。\n"
        "- 文末必须包含「风险提示」和不构成投资建议的免责声明。\n"
        "- 报告要完整收尾，不要写到一半中断。"
    ),
    expected_output=(
        "一份完整、可直接发送客户的每日美股复盘报告 MARKDOWN："
        "含规范的指数表格与指数 K 线图、往期预测验证表、六大章节、明确点位/数据、"
        "风险提示与免责声明，且已完整结尾。"
    ),
    agent=writer,
    context=[analyzer_task, review_task],
    output_file="outputs/03_report_{today}.md",
)

# ══════════════════════════════════════════════════════════════════════════════
# 任务 6：交付（独立成任务，确保一定调用发送工具）
# ══════════════════════════════════════════════════════════════════════════════
deliver_task = Task(
    description=(
        "上游任务已经产出完整的《美股复盘 | {today}》报告正文，并已保存为文件 "
        "outputs/03_report_{today}.md（见上下文）。你**只做交付**，不要重写报告、"
        "不要在最终回答里粘贴全文：\n\n"
        "1. 调用 save_report_file：source_file = outputs/03_report_{today}.md，"
        "filename = 美股复盘_{today}.md，content = 上游报告的完整正文。\n"
        "2. 调用 send_email_report：subject = 美股复盘 | {today} 大盘回顾与操作策略，"
        "**content 留空**，source_file = 上一步 save_report_file 返回的报告路径。\n"
        "3. 最终回答只需一句话，汇报「存档路径 + 邮件发送结果」。\n\n"
        "提示：优先用 source_file 传大段文本，避免把超长正文塞进工具参数导致解析失败。"
    ),
    expected_output="一句话交付结果：报告存档路径 + 邮件是否发送成功。",
    agent=writer,
    context=[writer_task],
    output_file="outputs/04_delivery_{today}.md",
)

TASKS = [researcher_task, fact_check_task, review_task, analyzer_task,
         writer_task, deliver_task]
